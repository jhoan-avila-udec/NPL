import time
def resumir_comentarios_video(video_id, cantidad_comentarios=10):
    """
    Resume en español los comentarios con más likes de un video.
    """

    # Buscar información del video
    registro_video = datos_youtube[
        datos_youtube["Video ID"] == video_id
    ]

    if registro_video.empty:
        return {
            "Error": "No se encontró el video solicitado."
        }

    # Seleccionar comentarios con mayor interacción
    comentarios_video = (
        comentarios_limpios[
            comentarios_limpios["Video ID"] == video_id
        ]
        .sort_values("Likes", ascending=False)
        .head(cantidad_comentarios)
    )

    if comentarios_video.empty:
        return {
            "Error": "El video no tiene comentarios disponibles."
        }

    titulo = registro_video.iloc[0]["Title"]

    texto_comentarios = "\n".join(
        f"- {comentario}"
        for comentario in comentarios_video["Comment"].astype(str)
    )

    prompt_resumen = f"""
    Analiza los siguientes comentarios relacionados con el video
    titulado: "{titulo}".

    Genera un resumen en español de máximo 120 palabras.

    El resumen debe:
    1. Explicar la opinión general de los usuarios.
    2. Mencionar los aspectos positivos más frecuentes.
    3. Mencionar las críticas o preocupaciones.
    4. No inventar información que no aparezca en los comentarios.

    Comentarios:
    {texto_comentarios}
    """

    inicio = time.time()

    try:
        respuesta = client.models.generate_content(
            model="gemini-3.8-flash",
            contents=prompt_resumen
        )

        tiempo = time.time() - inicio

        return {
            "Video ID": video_id,
            "Título": titulo,
            "Comentarios utilizados": len(comentarios_video),
            "Resumen": respuesta.text,
            "Tiempo de respuesta": round(tiempo, 2),
            "Estado": "Exitoso"
        }

    except Exception as error:
        return {
            "Video ID": video_id,
            "Título": titulo,
            "Comentarios utilizados": len(comentarios_video),
            "Resumen": None,
            "Tiempo de respuesta": round(time.time() - inicio, 2),
            "Estado": "Fallido",
            "Error": str(error)
        }

