"""## ❓ 10. Question Answering

Question Answering permite formular una pregunta sobre un texto y extraer una respuesta directamente del contexto proporcionado. En este ejercicio se utilizarán los comentarios asociados a un video como contexto.

Debido a que los comentarios del conjunto de datos están escritos principalmente en inglés, se utiliza un modelo entrenado para responder preguntas en ese idioma.
"""

#CODIGO TERCER BLOQUE (QA)

from transformers import (
    AutoTokenizer,
    AutoModelForQuestionAnswering
)

import torch

# Seleccionar GPU o CPU
dispositivo_qa = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)

nombre_modelo_qa = "distilbert-base-cased-distilled-squad"

# Descargar el tokenizador y el modelo directamente
tokenizador_qa = AutoTokenizer.from_pretrained(
    nombre_modelo_qa
)

modelo_qa = AutoModelForQuestionAnswering.from_pretrained(
    nombre_modelo_qa
)

modelo_qa.to(dispositivo_qa)
modelo_qa.eval()

print("Modelo de Question Answering cargado correctamente.")
print("Dispositivo utilizado:", dispositivo_qa)

def responder_pregunta_video(video_id, pregunta, cantidad_comentarios=5):
    """
    Responde una pregunta utilizando los comentarios con más likes
    del video seleccionado.
    """

    # Buscar el video
    registro_video = datos_youtube[
        datos_youtube["Video ID"] == video_id
    ]

    if registro_video.empty:
        return {
            "Error": "No se encontró el video solicitado."
        }

    # Seleccionar los comentarios con mayor cantidad de likes
    comentarios_video = (
        comentarios_limpios[
            comentarios_limpios["Video ID"] == video_id
        ]
        .sort_values("Likes", ascending=False)
        .head(cantidad_comentarios)
    )

    if comentarios_video.empty:
        return {
            "Error": "El video no tiene comentarios disponibles."
        }

    # Crear el contexto
    contexto = " ".join(
        comentarios_video["Comment"].astype(str).tolist()
    )

    # Tokenizar pregunta y contexto
    entradas = tokenizador_qa(
        pregunta,
        contexto,
        return_tensors="pt",
        truncation=True,
        max_length=512
    )

    entradas = {
        nombre: tensor.to(dispositivo_qa)
        for nombre, tensor in entradas.items()
    }

    # Realizar inferencia
    with torch.no_grad():
        salida = modelo_qa(**entradas)

    probabilidades_inicio = torch.softmax(
        salida.start_logits,
        dim=-1
    )[0]

    probabilidades_fin = torch.softmax(
        salida.end_logits,
        dim=-1
    )[0]

    posicion_inicio = int(
        torch.argmax(probabilidades_inicio)
    )

    posicion_fin = int(
        torch.argmax(probabilidades_fin)
    )

    # Evitar una respuesta con posiciones inválidas
    if posicion_fin < posicion_inicio:
        posicion_fin = posicion_inicio

    tokens_respuesta = entradas["input_ids"][0][
        posicion_inicio:posicion_fin + 1
    ]

    respuesta = tokenizador_qa.decode(
        tokens_respuesta,
        skip_special_tokens=True
    )

    confianza = (
        probabilidades_inicio[posicion_inicio]
        * probabilidades_fin[posicion_fin]
    ).item()

    return {
        "Video ID": video_id,
        "Título": registro_video.iloc[0]["Title"],
        "Pregunta": pregunta,
        "Respuesta": respuesta,
        "Confianza": round(confianza, 4),
        "Comentarios utilizados": len(comentarios_video)
    }

video_ejemplo = datos_youtube.iloc[0]

resultado_qa = responder_pregunta_video(
    video_id=video_ejemplo["Video ID"],
    pregunta="What do viewers say about Apple Pay?"
)

print("RESULTADO DE QUESTION ANSWERING")
print("--------------------------------")

for clave, valor in resultado_qa.items():
    print(f"{clave}: {valor}")

